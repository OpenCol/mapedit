#!/usr/bin/env python3
"""What the objects use that nothing defines: the M2 list, and weak stubs for the tests.

    python3 tools/unresolved.py OBJECT...                 # the list, by kind
    python3 tools/unresolved.py --stubs out.c OBJECT...   # weak definitions for each of them

A symbol is unresolved when an object uses it, no object defines it, and the C library
does not provide it. Until the editor links (M2), the oracle library is built with weak
stubs in their place, so it loads, and a test that reaches one fails loudly: a stub function
aborts, a stub variable is a zeroed block.
"""
import argparse, ctypes, ctypes.util, subprocess, sys


def symbols(objs):
    defined, used = set(), set()
    out = subprocess.run(['nm', '-g', '-P'] + objs, capture_output=True, text=True).stdout
    for line in out.splitlines():
        parts = line.split()
        if len(parts) < 2 or parts[0].endswith(':'):
            continue
        name, kind = parts[0], parts[1]
        (used if kind == 'U' else defined).add(name)
    return defined, used


def system_has(name):
    libc = ctypes.CDLL(None)
    try:
        getattr(libc, name)
        return True
    except AttributeError:
        return False


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument('objects', nargs='+')
    ap.add_argument('--stubs')
    a = ap.parse_args()
    defined, used = symbols(a.objects)
    strip = sys.platform == 'darwin'                    # Mach-O prefixes C names with _
    missing = sorted(n for n in used - defined
                     if not system_has(n[1:] if strip and n.startswith('_') else n))
    names = [n[1:] if strip and n.startswith('_') else n for n in missing]
    if a.stubs:
        with open(a.stubs, 'w') as f:
            f.write('/* generated by tools/unresolved.py: weak stand-ins for what nothing defines yet */\n'
                    '#include <stdio.h>\n#include <stdlib.h>\n\n')
            for n in names:
                if n.startswith('msc_'):
                    f.write('void %s(void) __attribute__((weak));\n'
                            'void %s(void) { fprintf(stderr, "unresolved: %s\\n"); abort(); }\n' % (n, n, n))
                else:
                    # a function or a variable: a zeroed block serves a variable, and calling it
                    # faults, which is what an unwritten function should do in a test
                    f.write('__attribute__((weak, aligned(16))) char %s[4096];\n' % n)
        print('%d unresolved symbols -> %s' % (len(names), a.stubs))
    else:
        for n in names:
            print(n)
        print('%d unresolved' % len(names), file=sys.stderr)


if __name__ == '__main__':
    main()
